import numpy as np


class DataAnalytics:
    def __init__(self, array=None):
        if array is None:
            self.array = np.array([])
        else:
            self.array = np.array(array)


    def create_array(self):
        print("\n1. 1D Array")
        print("2. 2D Array")
        print("3. 3D Array")

        choice = input("Choose array type: ")

        if choice == "1":
            values = input("Enter numbers separated by spaces: ")
            self.array = np.array(list(map(float, values.split())))

        elif choice == "2":
            rows = int(input("Enter number of rows: "))
            cols = int(input("Enter number of columns: "))
            values = list(map(float, input("Enter numbers: ").split()))

            if len(values) != rows * cols:
                print("Error: Incorrect number of elements.")
                return

            self.array = np.array(values).reshape(rows, cols)

        elif choice == "3":
            d1 = int(input("Enter depth: "))
            d2 = int(input("Enter rows: "))
            d3 = int(input("Enter columns: "))
            values = list(map(float, input("Enter numbers: ").split()))

            if len(values) != d1 * d2 * d3:
                print("Error: Incorrect number of elements.")
                return

            self.array = np.array(values).reshape(d1, d2, d3)

        else:
            print("Invalid choice.")
            return

        print("Array created successfully!")
        print(self.array)


    def display_array(self):
        print("Current Array:", self.array)
        print("Dimensions:", self.array.ndim)
        print("Shape:", self.array.shape)
        print("Size:", self.array.size)


    def indexing_slicing(self):
        if self.array.size == 0:
            print("Please create an array first.")
            return

        print("Array:", self.array)
        index = int(input("Enter index of flattened array: "))
        flat = self.array.flatten()

        if 0 <= index < len(flat):
            print("Element:", flat[index])
        else:
            print("Invalid index.")

        start = int(input("Enter slice start index: "))
        end = int(input("Enter slice end index: "))
        print("Slice:", flat[start:end])


    def combine_arrays(self):
        a = list(map(float, input("Enter first array: ").split()))
        b = list(map(float, input("Enter second array: ").split()))

        print("Combined Array:", np.concatenate((a, b)))


    def split_array(self):
        values = list(map(float, input("Enter numbers: ").split()))
        parts = int(input("Enter number of parts: "))

        if parts <= 0 or len(values) % parts != 0:
            print("Array cannot be split equally.")
            return

        print("Split Arrays:", np.split(np.array(values), parts))


    def mathematical_operations(self):
        if self.array.size == 0:
            print("Please create an array first.")
            return

        number = float(input("Enter a number: "))

        print("Addition:", self.array + number)
        print("Subtraction:", self.array - number)
        print("Multiplication:", self.array * number)

        if number != 0:
            print("Division:", self.array / number)
        else:
            print("Division by zero is not allowed.")

        if self.array.ndim == 2 and self.array.shape[0] == self.array.shape[1]:
            print("Matrix multiplication:", self.array @ self.array)


    def search_sort_filter(self):
        if self.array.size == 0:
            print("Please create an array first.")
            return

        flat = self.array.flatten()

        value = float(input("Enter value to search: "))
        print("Search result:", np.where(flat == value))

        print("Ascending:", np.sort(flat))
        print("Descending:", np.sort(flat)[::-1])

        limit = float(input("Filter values greater than: "))
        print("Filtered values:", flat[flat > limit])


    def __calculate_statistics(self):
        return {
            "Sum": np.sum(self.array),
            "Mean": np.mean(self.array),
            "Median": np.median(self.array),
            "Standard Deviation": np.std(self.array),
            "Variance": np.var(self.array),
            "Minimum": np.min(self.array),
            "Maximum": np.max(self.array),
            "25th Percentile": np.percentile(self.array, 25),
            "75th Percentile": np.percentile(self.array, 75)
        }


    def statistical_analysis(self):
        if self.array.size == 0:
            print("Please create an array first.")
            return

        results = self.__calculate_statistics()

        print("\nStatistical Analysis")
        for name, value in results.items():
            print(f"{name}: {value}")


    def correlation(self):
        a = list(map(float, input("Enter first array: ").split()))
        b = list(map(float, input("Enter second array: ").split()))

        if len(a) != len(b) or len(a) < 2:
            print("Arrays must have equal lengths of at least 2.")
            return

        result = np.corrcoef(a, b)[0, 1]
        print("Correlation Coefficient:", result)


    @classmethod
    def project_name(cls):
        return "NumPy Analyzer"


    @staticmethod
    def welcome():
        print("\nWelcome to the NumPy Analyzer!")


    def menu(self):
        while True:
            print("\n========== NUMPY ANALYZER ==========")
            print("1. Create Array")
            print("2. Display Array")
            print("3. Indexing and Slicing")
            print("4. Combine Arrays")
            print("5. Split Array")
            print("6. Mathematical Operations")
            print("7. Search, Sort and Filter")
            print("8. Statistical Analysis")
            print("9. Correlation")
            print("10. Project Information")
            print("0. Exit")

            choice = input("Enter your choice: ")

            try:
                if choice == "1":
                    self.create_array()
                elif choice == "2":
                    self.display_array()
                elif choice == "3":
                    self.indexing_slicing()
                elif choice == "4":
                    self.combine_arrays()
                elif choice == "5":
                    self.split_array()
                elif choice == "6":
                    self.mathematical_operations()
                elif choice == "7":
                    self.search_sort_filter()
                elif choice == "8":
                    self.statistical_analysis()
                elif choice == "9":
                    self.correlation()
                elif choice == "10":
                    print(self.project_name())
                    print("Built using Python, NumPy and OOP.")
                elif choice == "0":
                    print("Thank you for using NumPy Analyzer!")
                    break
                else:
                    print("Invalid choice. Try again.")

            except (ValueError, IndexError) as error:
                print("Invalid input:", error)



if __name__ == "__main__":
    DataAnalytics.welcome()
    analyzer = DataAnalytics()
    analyzer.menu()
